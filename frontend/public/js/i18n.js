class I18nManager {
  constructor() {
    this.registry = I18N_REGISTRY;
    this.currentLang = this.detectInitialLanguage();
    this.subscribers = [];
  }

  detectInitialLanguage() {
    // Check URL parameter
    const urlParams = new URLSearchParams(window.location.search);
    const langParam = urlParams.get('lang');
    if (langParam && this.registry.some(l => l.code === langParam)) {
      return langParam;
    }

    // Check localStorage
    try {
      const stored = localStorage.getItem('boardrank_lang');
      if (stored && this.registry.some(l => l.code === stored)) {
        return stored;
      }
    } catch (e) {
      // Storage unavailable
    }

    // Check browser language
    const browserLang = (navigator.language || navigator.userLanguage || 'en').split('-')[0].toLowerCase();
    if (this.registry.some(l => l.code === browserLang)) {
      return browserLang;
    }

    return 'en';
  }

  getLangMeta(code = this.currentLang) {
    return this.registry.find(l => l.code === code) || this.registry[0];
  }

  t(key, fallback = '') {
    const dict = TRANSLATIONS[this.currentLang] || TRANSLATIONS.en;
    if (dict && dict[key]) {
      return dict[key];
    }
    // Fallback to English
    if (TRANSLATIONS.en && TRANSLATIONS.en[key]) {
      return TRANSLATIONS.en[key];
    }
    return fallback || key;
  }

  formatNumber(value, options = {}) {
    try {
      return new Intl.NumberFormat(this.currentLang, options).format(value);
    } catch (e) {
      return value.toLocaleString();
    }
  }

  formatDate(date, options = {}) {
    try {
      return new Intl.DateTimeFormat(this.currentLang, options).format(date);
    } catch (e) {
      return new Date(date).toLocaleDateString();
    }
  }

  setLanguage(langCode) {
    const meta = this.getLangMeta(langCode);
    if (!meta) return;

    this.currentLang = meta.code;

    // Persist in localStorage
    try {
      localStorage.setItem('boardrank_lang', meta.code);
    } catch (e) {}

    // Update URL query state without full reload
    const url = new URL(window.location);
    url.searchParams.set('lang', meta.code);
    window.history.replaceState({}, '', url);

    // Apply document direction and lang attribute
    document.documentElement.setAttribute('lang', meta.code);
    document.documentElement.setAttribute('dir', meta.dir);
    document.body.classList.toggle('is-rtl', meta.dir === 'rtl');

    // Update all DOM elements with data-i18n
    this.translateDOM();

    // Notify listeners
    this.subscribers.forEach(cb => cb(meta));
  }

  translateDOM() {
    // Elements with text content
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const translation = this.t(key);
      if (translation) {
        // If element has nested icons or spans with keep-content class, respect them
        if (el.dataset.i18nTarget === 'placeholder') {
          el.placeholder = translation;
        } else if (el.dataset.i18nTarget === 'title') {
          el.title = translation;
        } else if (el.dataset.i18nTarget === 'aria') {
          el.setAttribute('aria-label', translation);
        } else {
          el.textContent = translation;
        }
      }
    });

    // Inputs with placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      const translation = this.t(key);
      if (translation) el.placeholder = translation;
    });

    // Elements with title attributes
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      const translation = this.t(key);
      if (translation) el.title = translation;
    });
  }

  onLanguageChange(callback) {
    this.subscribers.push(callback);
  }
}

export const i18n = new I18nManager();
